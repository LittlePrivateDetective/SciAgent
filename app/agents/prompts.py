ANSWER_PROMPT = """【证据】
{evidence}

【问题】
{question}

要求：
- 证据由 PDF 切块而来，可能从半句开始（如 "ence pairs containing…"）；请通读整段，
  并优先看每条证据下方的「▸ 关键句」，不要只看开头就判定"未提及"。
- 第一句直接给结论（能一句话答完就一句话），不要写"根据提供的证据…""受证据限制…"这类前言。
- 问「是多少 / 多大 / 几个 / 什么规模」时：证据里出现数值或符号表达式，第一句必须原样给出
  （例如 `O(n²·d)`、`512`、`8 个`）；证据里确实没有，就直说"证据未给出具体数值"。
  既不要用"与…相当""取决于…"含糊带过，也不要自己推算一个填上——后者比含糊更严重。
- 证据里**并列列出**的技术、条件、步骤、指标要全部列出，不要只挑前两项；
  列举不全比多写一句更丢分。
- 标了「【表格】」的证据是逐行拼出来的：同一行内用 ｜ 分隔的单元格属于同一组，
  行与行之间按顺序对应。问到数值/复杂度/规模时，**先在表格里按行找**，
  找到就直接引用该行，不要因为"句子不像完整表述"就判定未提及。
- 结论后面用 1-3 个要点给依据，每点末尾必须带 [编号]。
- 证据充分时就要确定地回答，不要用"可能/大概/未明确说明"来对冲；只有通读全部证据后确实没有的信息，才写一句"文献中未提及 X"。
- 涉及数字/超参/型号时，原样抄写证据中的写法（包括单位），不做换算或四舍五入。
- 全文控制在 300 字以内，不要罗列与问题无关的证据。

输出 JSON：
{{"answer": "正文（含 [1] 这样的引用标记）", "confidence": "high|medium|low",
 "missing": "证据中缺失的关键信息，没有就留空"}}"""


